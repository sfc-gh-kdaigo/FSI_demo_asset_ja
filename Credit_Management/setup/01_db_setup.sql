USE SCHEMA CREDIT_DATA;

-- ---------------------------------------------------------
-- Step 2-1: 法人顧客マスタ
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE CUSTOMER (
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    CUSTOMER_NAME        VARCHAR        NOT NULL  COMMENT '企業名',
    CUSTOMER_TYPE        VARCHAR                  COMMENT '顧客区分（法人/個人事業主）',
    INDUSTRY_CODE        VARCHAR                  COMMENT '業種コード',
    INDUSTRY_NAME        VARCHAR        NOT NULL  COMMENT '業種名',
    SUB_INDUSTRY         VARCHAR                  COMMENT '業種詳細',
    CAPITAL              NUMBER(15,0)             COMMENT '資本金（百万円）',
    EMPLOYEE_COUNT       NUMBER(10,0)             COMMENT '従業員数',
    ANNUAL_REVENUE       NUMBER(15,0)             COMMENT '年間売上高（百万円）',
    ESTABLISHED_DATE     DATE                     COMMENT '設立日',
    PREFECTURE           VARCHAR                  COMMENT '所在都道府県',
    CREDIT_RATING        VARCHAR                  COMMENT '信用格付（AAA〜D）',
    CREDIT_SCORE         NUMBER(5,1)              COMMENT '信用スコア（0〜100）',
    RATING_DATE          DATE                     COMMENT '格付更新日',
    RISK_SEGMENT         VARCHAR                  COMMENT 'リスクセグメント（正常先/要注意先/要管理先/破綻懸念先/実質破綻先/破綻先）',
    RELATIONSHIP_MANAGER VARCHAR                  COMMENT '担当RM',
    BRANCH_NAME          VARCHAR                  COMMENT '担当支店',
    STATUS               VARCHAR        DEFAULT 'ACTIVE' COMMENT 'ステータス（ACTIVE/INACTIVE）',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_customer PRIMARY KEY (CUSTOMER_ID)
) COMMENT = '法人顧客マスタ';

-- ---------------------------------------------------------
-- Step 2-2: 融資情報
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE LOAN (
    LOAN_ID              NUMBER(10,0)   NOT NULL  COMMENT '融資ID',
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    LOAN_TYPE            VARCHAR        NOT NULL  COMMENT '融資種別（証書貸付/手形貸付/当座貸越/割引手形）',
    LOAN_PURPOSE         VARCHAR                  COMMENT '資金使途（運転資金/設備資金/不動産/M&A）',
    LOAN_PURPOSE_DETAIL  VARCHAR                  COMMENT '資金使途詳細',
    LOAN_AMOUNT          NUMBER(15,0)   NOT NULL  COMMENT '融資金額（百万円）',
    OUTSTANDING_BALANCE  NUMBER(15,0)   NOT NULL  COMMENT '融資残高（百万円）',
    INTEREST_RATE        NUMBER(5,3)              COMMENT '適用金利（%）',
    RATE_TYPE            VARCHAR                  COMMENT '金利区分（固定/変動）',
    LOAN_START_DATE      DATE           NOT NULL  COMMENT '融資実行日',
    LOAN_END_DATE        DATE                     COMMENT '返済期限',
    REPAYMENT_METHOD     VARCHAR                  COMMENT '返済方法（元金均等/元利均等/期日一括）',
    LOAN_STATUS          VARCHAR        NOT NULL  COMMENT 'ステータス（正常/延滞/条件変更/代位弁済/償却）',
    DAYS_PAST_DUE        NUMBER(5,0)    DEFAULT 0 COMMENT '延滞日数',
    ASSET_CLASSIFICATION VARCHAR                  COMMENT '債務者区分（正常先/要注意先/破綻懸念先/実質破綻先/破綻先）',
    RECORD_DATE          DATE           NOT NULL  COMMENT '記録基準日',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_loan PRIMARY KEY (LOAN_ID, RECORD_DATE)
) COMMENT = '融資情報';

-- ---------------------------------------------------------
-- Step 2-3: 財務諸表
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE FINANCIAL_STATEMENT (
    FS_ID                NUMBER(10,0)   NOT NULL  COMMENT '財務ID',
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    FISCAL_YEAR_END      DATE           NOT NULL  COMMENT '決算期末日',
    TOTAL_ASSETS         NUMBER(15,0)             COMMENT '総資産（百万円）',
    NET_ASSETS           NUMBER(15,0)             COMMENT '純資産（百万円）',
    REVENUE              NUMBER(15,0)             COMMENT '売上高（百万円）',
    OPERATING_PROFIT     NUMBER(15,0)             COMMENT '営業利益（百万円）',
    NET_INCOME           NUMBER(15,0)             COMMENT '当期純利益（百万円）',
    CURRENT_ASSETS       NUMBER(15,0)             COMMENT '流動資産（百万円）',
    CURRENT_LIABILITIES  NUMBER(15,0)             COMMENT '流動負債（百万円）',
    TOTAL_DEBT           NUMBER(15,0)             COMMENT '有利子負債（百万円）',
    CASH_FLOW_OPERATING  NUMBER(15,0)             COMMENT '営業CF（百万円）',
    EQUITY_RATIO         NUMBER(5,1)              COMMENT '自己資本比率（%）',
    CURRENT_RATIO        NUMBER(5,1)              COMMENT '流動比率（%）',
    DEBT_EQUITY_RATIO    NUMBER(5,2)              COMMENT 'DEレシオ',
    INTEREST_COVERAGE    NUMBER(8,2)              COMMENT 'インタレストカバレッジレシオ',
    ROA                  NUMBER(5,2)              COMMENT 'ROA（%）',
    ROE                  NUMBER(5,2)              COMMENT 'ROE（%）',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_financial_statement PRIMARY KEY (FS_ID)
) COMMENT = '財務諸表（年次）';

-- ---------------------------------------------------------
-- Step 2-4: 口座取引
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE ACCOUNT_TRANSACTION (
    TXN_ID               NUMBER(10,0)   NOT NULL  COMMENT '取引ID',
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    TXN_DATE             DATE           NOT NULL  COMMENT '取引日',
    TXN_TYPE             VARCHAR        NOT NULL  COMMENT '入出金区分（入金/出金）',
    AMOUNT               NUMBER(15,0)   NOT NULL  COMMENT '取引金額（百万円）',
    BALANCE_AFTER        NUMBER(15,0)             COMMENT '取引後残高（百万円）',
    CATEGORY             VARCHAR                  COMMENT '取引カテゴリ（売上入金/仕入支払/給与/税金/借入返済/その他）',
    MEMO                 VARCHAR                  COMMENT '摘要',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_account_transaction PRIMARY KEY (TXN_ID)
) COMMENT = '口座取引（月次サマリー）';

-- ---------------------------------------------------------
-- Step 2-5: 担保情報
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE COLLATERAL (
    COLLATERAL_ID        NUMBER(10,0)   NOT NULL  COMMENT '担保ID',
    LOAN_ID              NUMBER(10,0)   NOT NULL  COMMENT '融資ID',
    COLLATERAL_TYPE      VARCHAR        NOT NULL  COMMENT '担保種別（不動産/有価証券/預金/売掛金/在庫）',
    DESCRIPTION          VARCHAR                  COMMENT '担保物件の概要',
    APPRAISED_VALUE      NUMBER(15,0)             COMMENT '評価額（百万円）',
    HAIRCUT_RATE         NUMBER(5,1)              COMMENT '掛目（%）',
    SECURED_VALUE        NUMBER(15,0)             COMMENT '担保価値（百万円）',
    APPRAISAL_DATE       DATE                     COMMENT '直近評価日',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_collateral PRIMARY KEY (COLLATERAL_ID)
) COMMENT = '担保情報';

-- ---------------------------------------------------------
-- Step 2-6: 返済実績
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE REPAYMENT (
    REPAYMENT_ID         NUMBER(10,0)   NOT NULL  COMMENT '返済ID',
    LOAN_ID              NUMBER(10,0)   NOT NULL  COMMENT '融資ID',
    DUE_DATE             DATE           NOT NULL  COMMENT '約定返済日',
    ACTUAL_DATE          DATE                     COMMENT '実際の返済日',
    DUE_AMOUNT           NUMBER(15,0)   NOT NULL  COMMENT '約定返済額（百万円）',
    ACTUAL_AMOUNT        NUMBER(15,0)             COMMENT '実際の返済額（百万円）',
    PRINCIPAL_PORTION    NUMBER(15,0)             COMMENT '元金部分（百万円）',
    INTEREST_PORTION     NUMBER(15,0)             COMMENT '利息部分（百万円）',
    STATUS               VARCHAR        NOT NULL  COMMENT 'ステータス（正常/延滞/一部返済）',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_repayment PRIMARY KEY (REPAYMENT_ID)
) COMMENT = '返済実績';

-- ---------------------------------------------------------
-- Step 2-7: 審査履歴
-- ---------------------------------------------------------
CREATE OR REPLACE TABLE CREDIT_REVIEW (
    REVIEW_ID            NUMBER(10,0)   NOT NULL  COMMENT '審査ID',
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    LOAN_ID              NUMBER(10,0)             COMMENT '融資ID（新規審査時は対象融資）',
    REVIEW_DATE          DATE           NOT NULL  COMMENT '審査日',
    REVIEW_TYPE          VARCHAR        NOT NULL  COMMENT '審査種別（新規審査/期中審査/格付更新/緊急審査）',
    PREVIOUS_RATING      VARCHAR                  COMMENT '審査前格付',
    NEW_RATING           VARCHAR                  COMMENT '審査後格付',
    DECISION             VARCHAR        NOT NULL  COMMENT '審査結果（承認/条件付承認/否決/保留）',
    REVIEWER             VARCHAR                  COMMENT '審査担当者',
    APPROVER             VARCHAR                  COMMENT '承認者',
    REVIEW_COMMENT       TEXT                     COMMENT '審査コメント',
    RISK_FACTORS         TEXT                     COMMENT 'リスク要因',
    CONDITIONS           TEXT                     COMMENT '条件事項',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_credit_review PRIMARY KEY (REVIEW_ID)
) COMMENT = '審査履歴';

-- ---------------------------------------------------------
-- Step 2-8: 面談記録（Cortex Search 用テキスト）
-- ---------------------------------------------------------
USE SCHEMA DOCUMENTS;

CREATE OR REPLACE TABLE MEETING_NOTE (
    NOTE_ID              NUMBER(10,0)   NOT NULL  COMMENT 'ノートID',
    CUSTOMER_ID          NUMBER(10,0)   NOT NULL  COMMENT '顧客ID',
    CUSTOMER_NAME        VARCHAR                  COMMENT '企業名',
    MEETING_DATE         DATE           NOT NULL  COMMENT '面談日',
    ATTENDEES            VARCHAR                  COMMENT '出席者',
    MEETING_CONTENT      TEXT           NOT NULL  COMMENT '面談内容（詳細メモ）',
    KEY_POINTS           TEXT                     COMMENT '重要ポイント',
    NEXT_ACTION          VARCHAR                  COMMENT 'ネクストアクション',
    KEYWORDS             VARCHAR                  COMMENT 'キーワード',
    CREATED_AT           TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT pk_meeting_note PRIMARY KEY (NOTE_ID)
) COMMENT = '面談記録（Cortex Search 用）';


