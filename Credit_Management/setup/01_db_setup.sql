USE SCHEMA CREDIT_DATA;

-- 顧客一覧（業種別）
SELECT
    INDUSTRY_NAME,
    COUNT(*)                          AS 顧客数,
    SUM(ANNUAL_REVENUE)               AS 売上合計_百万円,
    LISTAGG(CREDIT_RATING, ', ')
        WITHIN GROUP (ORDER BY CREDIT_SCORE DESC) AS 格付一覧
FROM CUSTOMER
GROUP BY INDUSTRY_NAME
ORDER BY 売上合計_百万円 DESC;

-- 融資残高 TOP10
SELECT
    c.CUSTOMER_NAME                   AS 企業名,
    c.INDUSTRY_NAME                   AS 業種,
    c.CREDIT_RATING                   AS 格付,
    SUM(l.OUTSTANDING_BALANCE)        AS 融資残高_百万円,
    COUNT(l.LOAN_ID)                  AS 融資件数
FROM LOAN l
JOIN CUSTOMER c ON l.CUSTOMER_ID = c.CUSTOMER_ID
WHERE l.RECORD_DATE = '2025-01-31'
GROUP BY c.CUSTOMER_NAME, c.INDUSTRY_NAME, c.CREDIT_RATING
ORDER BY 融資残高_百万円 DESC
LIMIT 10;

-- 延滞先一覧
SELECT
    c.CUSTOMER_NAME                   AS 企業名,
    c.CREDIT_RATING                   AS 格付,
    c.RISK_SEGMENT                    AS リスクセグメント,
    l.LOAN_ID,
    l.OUTSTANDING_BALANCE             AS 融資残高_百万円,
    l.DAYS_PAST_DUE                   AS 延滞日数,
    l.ASSET_CLASSIFICATION            AS 債務者区分
FROM LOAN l
JOIN CUSTOMER c ON l.CUSTOMER_ID = c.CUSTOMER_ID
WHERE l.LOAN_STATUS IN ('延滞', '条件変更')
  AND l.RECORD_DATE = '2025-01-31'
ORDER BY l.DAYS_PAST_DUE DESC;

-- 財務推移（業績悪化先を確認）
SELECT
    c.CUSTOMER_NAME                   AS 企業名,
    fs.FISCAL_YEAR_END                AS 決算期末,
    fs.REVENUE                        AS 売上高,
    fs.OPERATING_PROFIT               AS 営業利益,
    fs.NET_INCOME                     AS 当期純利益,
    fs.EQUITY_RATIO                   AS 自己資本比率,
    fs.CURRENT_RATIO                  AS 流動比率
FROM FINANCIAL_STATEMENT fs
JOIN CUSTOMER c ON fs.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.CUSTOMER_ID IN (2006, 4004)
ORDER BY c.CUSTOMER_NAME, fs.FISCAL_YEAR_END;


